// City list is derived from the turf data so the filter stays dynamic.
export const locations = [...new Set(turfs.map((t) => t.location))].sort(
  (a, b) =>
    turfs.filter((t) => t.location === b).length - turfs.filter((t) => t.location === a).length,
);

export function turfCountByCity(city) {
  return turfs.filter((t) => t.location === city).length;
}

export function getTurfsByCity(city) {
  return city ? turfs.filter((t) => t.location === city) : turfs;
}

export function getTurfById(id) {
  return turfs.find((t) => t.id === String(id));
}
